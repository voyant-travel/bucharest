/** The names a destination box can legitimately resolve to on this vertical. */
const PLACES = PACKAGE_ROWS.flatMap((row) => [row.resort, row.country])

const BADGE_ORDER = ["recommended", "lastplaces", "earlybooking", "luxury"]

function badgeOf(row: PackageRow, copy: Copy, locale: string): string | undefined {
  const tag = BADGE_ORDER.find((candidate) => row.tags.includes(candidate))
  return tag ? labelFor(TAGS, tag, copy, locale) : undefined
}

function result(row: PackageRow, copy: Copy, locale: string): ResultItem {
  const transport = labelFor(TRANSPORT_TYPES, row.transport, copy, locale)
  const badge = badgeOf(row, copy, locale)
  const meal = labelFor(MEALS, row.meal, copy, locale)
  const nights = counted(locale, copy.plurals.nights, row.nights)
  return {
    id: row.id,
    title: row.hotel,
    href: `/oferte/${row.id}`,
    image: photo(row.image, `${row.hotel}, ${row.resort}`),
    ...(badge ? { badge } : {}),
    eyebrow: `${fill(copy.eyebrows.departing, { date: longDate(row.date, locale) })} · ${nights}`,
    place: `${row.resort}, ${row.country}`,
    classification: row.classification,
    rating: { score: row.score, label: ratingLabel(row.score, copy), count: row.reviews },
    inclusions: [
      fill(copy.inclusions.travelBy, { mode: transport.toLowerCase() }),
      meal,
      row.transfer === "included"
        ? copy.inclusions.airportTransfer
        : copy.inclusions.airportTaxes,
      copy.inclusions.cancellationCover,
    ],
    chips: [nights, meal, labelFor(CANCELLATIONS, row.cancellation, copy, locale)],
    price: {
      amount: row.price,
      currency: CURRENCY,
      basis: "per_stay",
      ...(row.was ? { was: row.was, discountPct: Math.round((1 - row.price / row.was) * 100) } : {}),
      footnote: copy.footnotes.packageTotal,
    },
    otherDates: row.otherDates,
  }
}

/**
 * The form's own narrowing, before any facet is considered.
 *
 * Flexible dates are handled here rather than as a facet because ±3 days is a
 * property of the search, not of the offer: a traveller who ticked it wants a
 * wider net, not another rail to manage.
 */
function base(row: PackageRow, query: SearchQuery): boolean {
  const filters = query.filters
  const destination = filters.destination
  if (typeof destination === "string" && destination !== "") {
    if (!matchesPlace(destination, [row.resort, row.country, row.hotel], PLACES)) return false
  }
  const departure = filters.departure
  if (typeof departure === "string" && departure !== "") {
    if (fold(row.departure) !== fold(departure)) return false
  }
  const date = filters.date
  if (typeof date === "string" && date !== "") {
    const wanted = Date.parse(date)
    const actual = Date.parse(row.date)
    if (!Number.isNaN(wanted) && !Number.isNaN(actual)) {
      const slack = filters.flex === true ? 3 : 0
      if (Math.abs(actual - wanted) > slack * 86_400_000) return false
    }
  }
  const duration = filters.duration
  if (typeof duration === "string" && !inBand(row.nights, duration)) return false
  if (typeof query.q === "string" && query.q !== "") {
    if (!contains(`${row.hotel} ${row.resort} ${row.country}`, query.q)) return false
  }
  return true
}

