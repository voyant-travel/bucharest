/**
 * Charter packages: a hotel, a seat and a transfer sold as one price.
 *
 * The row keeps the flight attached rather than referencing it, because on this
 * product the flight is not a separate purchase — a stopover in Istanbul is a
 * property of the offer, and the "Stops" and "Airlines" facets have to narrow
 * the same list as "Classification". Coach and own-transport departures simply
 * carry no flight, which is why those two facets can legitimately count zero
 * for part of the set.
 *
 * The rows are demo content. They are written in English, the theme's base
 * language, and they name only what a supplier feed would name: hotels,
 * resorts, countries, airlines. Every word around them — the board basis, the
 * ribbon, what is included — is the theme's own and is looked up per locale.
 */
