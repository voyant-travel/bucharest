/** Cities, areas and countries — the three things a destination box returns. */
const PLACES = STAY_ROWS.flatMap((row) => [row.city, row.country, row.area])

function result(row: StayRow, copy: Copy, locale: string): ResultItem {
  const badge = row.tags.includes("recommended")
    ? "recommended"
    : row.was
      ? "limitedoffer"
      : undefined
  const meal = labelFor(MEALS, row.meal, copy, locale)
  const cancellation = labelFor(CANCELLATIONS, row.cancellation, copy, locale)
  return {
    id: row.id,
    title: row.name,
    href: `/cazare/${row.id}`,
    image: photo(row.image, `${row.name}, ${row.city}`),
    ...(badge ? { badge: labelFor(BADGES, badge, copy, locale) } : {}),
    eyebrow: labelFor(HOTEL_TYPES, row.type, copy, locale),
    place: `${row.area}, ${row.city}`,
    classification: row.classification,
    rating: { score: row.score, label: ratingLabel(row.score, copy), count: row.reviews },
    inclusions: [
      meal,
      cancellation,
      row.pets ? copy.inclusions.petsWelcome : copy.inclusions.noPets,
    ],
    chips: [
      meal,
      cancellation,
      ...(row.amenities.includes("parking") ? [copy.inclusions.parking] : []),
    ],
    price: {
      amount: row.price,
      currency: CURRENCY,
      basis: "per_night",
      ...(row.was ? { was: row.was, discountPct: Math.round((1 - row.price / row.was) * 100) } : {}),
      footnote: copy.footnotes.perNight,
    },
    geo: { lat: row.lat, lng: row.lng },
  }
}

function base(row: StayRow, query: SearchQuery): boolean {
  const filters = query.filters
  const destination = filters.destination
  if (typeof destination === "string" && destination !== "") {
    const names = [row.city, row.country, row.area, row.name]
    if (!matchesPlace(destination, names, PLACES)) return false
  }
  /** The toggle is a hard constraint: a traveller with a dog cannot compromise. */
  if (filters.pets === true && !row.pets) return false
  return true
}

